import assert from 'node:assert/strict';
import fs from 'node:fs';
import {convertDump} from './convert-to-nani.mjs';
import {parseDump,findObjects,getCommandRids} from './parse-unity-dump.mjs';
const input=process.argv[2];
if(!input)throw Error('node test.mjs dump.txt');
const text=fs.readFileSync(input,'utf8');
const {files,report}=convertDump(text,{strict:true});
assert.equal(files.length,14);assert.equal(report.issues.length,0);
const objects=findObjects(parseDump(text).nodes).filter(o=>getCommandRids(o).length);
assert.equal(objects.reduce((n,o)=>n+getCommandRids(o).length,0),Object.values(report.commandCounts).reduce((a,b)=>a+b,0));
const sample=files.find(f=>f.filename.endsWith('_Adv10.nani')).content.split('\n');
assert.equal(sample[3],'# Scene1-4-10');assert.equal(sample[2],'');
assert.match(sample[0],/IsDebugDirectJump:\{isDebugDirectJump\}/);
assert.match(sample[15],/^\[PrintTextModified Text:エマが/);
assert.match(sample[19],/AuthorId:Margo/);
assert.ok(files.some(f=>f.content.includes('<ruby=')));
const aliased=convertDump(text,{aliases:{Gosub:{command:'gosub',parameters:{Path:''}}}}).files;
assert.match(aliased[0].content.split('\n')[1],/^@gosub System\/System_Subroutine.BeginAdv$/);
assert.throws(()=>convertDump(text.replace('path (string) Act01_Chapter04/Act01_Chapter04_Adv10','path (string) ../escape')),/Unsafe script path/);
assert.throws(()=>convertDump(text.replaceAll('rid (SInt64) 1000','rid (SInt64) 999999999'),{strict:true}),/Strict conversion failed/);
console.log('PASS: 14 scripts, playlist coverage, ordering, expressions, text, author, aliases, traversal and broken references');
